-- Phase 04 Task 10: publish participant-protected messages to Supabase Realtime.
-- Realtime authorization remains governed by the existing messages RLS policy.

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end;
$$;
